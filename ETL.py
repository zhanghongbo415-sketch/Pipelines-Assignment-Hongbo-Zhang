def incremental_upsert(new_df: pd.DataFrame, output_path: Path) -> pd.DataFrame:
    """
    Applies incremental loading patterns to local file persistence structures.
    Prevents duplicate records by identifying, appending, and updating records via time keys.
    """
    if output_path.exists():
        logger.info("Prior file system artifact detected. Applying high-performance state merge on path: %s", output_path)
        existing_df = pd.read_csv(output_path, parse_dates=["date"])
        existing_df = existing_df.set_index("date")

        # Combining historic context logs with the newly extracted execution stream delta
        combined_df = pd.concat([existing_df, new_df])

        # Key-deduplication strategy: Dropping duplicate records, updating to keep the latest entries
        combined_df = combined_df[~combined_df.index.duplicated(keep="last")]
        combined_df = combined_df.sort_index()
    else:
        logger.info("No prior file system artifact discovered. Initializing execution flow on path: %s", output_path)
        combined_df = new_df.sort_index()

    logger.info("Incremental delta processing block resolved %s operational rows.", len(combined_df))
    return combined_df


