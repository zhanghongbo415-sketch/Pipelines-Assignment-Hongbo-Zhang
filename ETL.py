def validate_clean_climate(daily_df: pd.DataFrame) -> None:
    """
    Runs multi-tiered validation rules enforcing robust quality invariants.
    Evaluates schema structure, missing properties, primary duplicates, and logical boundaries.
    """
    # Schema & Columns Validation Check
    required_columns = {
        "temp_max_f", "temp_min_f", "temp_mean_f", "temp_range_f",
        "precipitation_inches", "rain_inches", "snowfall_inches",
        "humidity_mean_pct", "wind_speed_mean_mph", "cloud_cover_pct",
        "weather_category_code", "weather_description",
    }
    missing_columns = required_columns.difference(daily_df.columns)
    if missing_columns:
        raise ValueError(f"Data schema invariant failure. Missing columns: {sorted(missing_columns)}")

    # Row Count Verification Check
    if daily_df.empty:
        raise ValueError("Data quality alert: Zero records found within processed frame.")

    # Null Value Verification Check
    if daily_df.index.isna().any():
        raise ValueError("Index anomaly: Null value detected within index components.")

    # Duplicate Record Detection Check
    duplicate_dates = daily_df.index[daily_df.index.duplicated()].unique()
    if len(duplicate_dates) > 0:
        raise ValueError(f"Primary entity constraint violation. Duplicate timestamps discovered: {list(duplicate_dates)}")

    # Comprehensive Null Value Verification across required structural fields
    required_non_null = [
        "temp_max_f", "temp_min_f", "temp_mean_f", "precipitation_inches",
        "humidity_mean_pct", "wind_speed_mean_mph", "cloud_cover_pct", "weather_description",
    ]
    null_counts = daily_df[required_non_null].isna().sum()
    if null_counts.any():
        raise ValueError(f"Data quality null constraint failure: {null_counts.to_dict()}")

    # Domain Range Validation Checks (Enforcing strict physical logic constraints)
    if (daily_df["temp_max_f"] < daily_df["temp_min_f"]).any():
        raise ValueError("Physical impossibility check failure: max temperature bounded under min temperature.")

    if (~daily_df["humidity_mean_pct"].between(0, 100, inclusive="both")).any():
        raise ValueError("Boundary error: Humidity percentages drifted outside defined [0, 100] coordinates.")

    if (~daily_df["cloud_cover_pct"].between(0, 100, inclusive="both")).any():
        raise ValueError("Boundary error: Cloud density values drifted outside defined [0, 100] coordinates.")

    for column in ["precipitation_inches", "rain_inches", "snowfall_inches"]:
        if (daily_df[column] < 0).any():
            raise ValueError(f"Mathematical sign error: Negative mass metric discovered within '{column}'.")

    logger.info("All programmatic Data Quality Engineering validation routines passed successfully.")


