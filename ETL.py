def main() -> None:
    """
    Main execution pipeline orchestrator managing execution state transitions.
    Wraps full workflows inside high-level exception trees to handle terminal failures cleanly.
    """
    try:
        logger.info("=== Executing Orchestration Chain: New Orleans Climate Analytical Pipeline ===")

        raw_response = extract_climate_data()
        validate_raw_response(raw_response)

        daily_df = clean_and_normalize_climate(raw_response)
        lookup_df = build_weather_category_lookup()
        daily_df = enrich_with_weather_descriptions(daily_df, lookup_df)


        validate_clean_climate(daily_df)


        weekly_df = build_weekly_aggregation(daily_df)
        recommendations_df = generate_activity_recommendations(daily_df)


        load_csv_outputs(daily_df, weekly_df, recommendations_df)
        load_postgresql_outputs(daily_df, weekly_df, recommendations_df)

        logger.info("Orchestration sequence completed successfully with zero terminal errors.")
        logger.info("Metrics Summary -> Operational Daily Rows: %s", len(daily_df))
        logger.info("Metrics Summary -> Aggregate Weekly Rows: %s", len(weekly_df))
        logger.info("Metrics Summary -> Recommendation Analytical Rows: %s", len(recommendations_df))

    except Exception:
        logger.exception("Pipeline master orchestrator encountered terminal panic state.")
        raise


if __name__ == "__main__":
    main()
