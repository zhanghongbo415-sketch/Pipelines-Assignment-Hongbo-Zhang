def validate_raw_response(raw_response: dict) -> None:
    """
    Performs critical structural validation on inbound API dictionary payloads.
    Verifies object structures, key requirements, and array row-count invariants.
    """
    if not isinstance(raw_response, dict):
        raise ValueError("API response must be a valid dictionary structure.")

    daily_data = raw_response.get("daily")
    if not daily_data:
        raise ValueError(f"Payload validation failed. Missing 'daily' payload key. Raw content: {raw_response}")

    # Structural Schema Validation Check
    required_fields = {
        "time",
        "temperature_2m_max",
        "temperature_2m_min",
        "temperature_2m_mean",
        "precipitation_sum",
        "rain_sum",
        "snowfall_sum",
        "wind_speed_10m_mean",
        "relative_humidity_2m_mean",
    }
    missing_fields = required_fields.difference(daily_data)
    if missing_fields:
        raise ValueError(f"Raw API structural mismatch. Missing attributes: {sorted(missing_fields)}")

    # Inbound Row Count Verification
    row_count = len(daily_data["time"])
    if row_count == 0:
        raise ValueError("Raw inbound payload contains zero observation records.")

    for field in required_fields:
        if len(daily_data[field]) != row_count:
            raise ValueError(f"Structural misalignment detected: attribute '{field}' violates length invariant.")

    logger.info("Raw response structural validation passed with %s elements.", row_count)


