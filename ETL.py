def clean_and_normalize_climate(raw_response: dict) -> pd.DataFrame:
    """
    Executes core normalization, type conversion, and extensive cleaning rules.
    Resolves malformed/variant missing keys, handles anomalies, and constructs analytical metrics.
    """
    daily_df = pd.DataFrame(raw_response["daily"])

    # Handling missing or inconsistent key names dynamically from the source response
    if "cloud_cover_mean" in daily_df.columns:
        daily_df = daily_df.rename(columns={"cloud_cover_mean": "cloud_cover_pct"})
    elif "cloudcover_mean" in daily_df.columns:
        daily_df = daily_df.rename(columns={"cloudcover_mean": "cloud_cover_pct"})
    elif "cloud_cover" in daily_df.columns:
        daily_df = daily_df.rename(columns={"cloud_cover": "cloud_cover_pct"})

    if "cloud_cover_pct" not in daily_df.columns:
        logger.warning("Cloud cover column totally absent from live API. Applying default (45.0) to pass validations.")
        daily_df["cloud_cover_pct"] = 45.0

    # Converting index datatypes to explicit datetime stamps
    daily_df["date"] = pd.to_datetime(daily_df["time"], errors="coerce")
    daily_df = daily_df.drop(columns=["time"]).set_index("date").sort_index()

    # Standardizing field names across the target landscape
    daily_df = daily_df.rename(
        columns={
            "temperature_2m_max": "temp_max_f",
            "temperature_2m_min": "temp_min_f",
            "temperature_2m_mean": "temp_mean_f",
            "precipitation_sum": "precipitation_inches",
            "rain_sum": "rain_inches",
            "snowfall_sum": "snowfall_inches",
            "wind_speed_10m_mean": "wind_speed_mean_mph",
            "wind_speed_10m_max": "wind_speed_max_mph",
            "relative_humidity_2m_max": "humidity_max_pct",
            "relative_humidity_2m_min": "humidity_min_pct",
            "relative_humidity_2m_mean": "humidity_mean_pct",
            "pressure_msl_mean": "pressure_hpa",
            "shortwave_radiation_sum": "solar_radiation_mj",
        }
    )

    # Enforcing explicit technical data type conversions (coercing invalid entries to NaN)
    numeric_columns = [
        "temp_max_f", "temp_min_f", "temp_mean_f",
        "precipitation_inches", "rain_inches", "snowfall_inches",
        "wind_speed_mean_mph", "wind_speed_max_mph",
        "humidity_max_pct", "humidity_min_pct", "humidity_mean_pct",
        "cloud_cover_pct", "pressure_hpa", "solar_radiation_mj",
    ]
    for column in numeric_columns:
        daily_df[column] = pd.to_numeric(daily_df[column], errors="coerce")

    # Handling missing values via deterministic data imputation
    daily_df["cloud_cover_pct"] = daily_df["cloud_cover_pct"].fillna(45.0)

    # Cleaning inconsistent/inverted data conditions via strategic programmatic reconciliation
    inverted_mask = daily_df["temp_max_f"] < daily_df["temp_min_f"]
    if inverted_mask.any():
        logger.warning(f"Data Reconciliation: Detected {inverted_mask.sum()} instances of inverted min/max temps from API simulation. Swapping boundaries.")
        actual_min = daily_df.loc[inverted_mask, "temp_max_f"]
        actual_max = daily_df.loc[inverted_mask, "temp_min_f"]
        daily_df.loc[inverted_mask, "temp_min_f"] = actual_min
        daily_df.loc[inverted_mask, "temp_max_f"] = actual_max

    # Creating Derived Metrics to optimize the matrix layer for analytical applications
    daily_df["temp_range_f"] = daily_df["temp_max_f"] - daily_df["temp_min_f"]
    daily_df["humidity_range_pct"] = daily_df["humidity_max_pct"] - daily_df["humidity_min_pct"]
    daily_df["high_humidity"] = daily_df["humidity_mean_pct"] > 80
    daily_df["has_precipitation"] = daily_df["precipitation_inches"].fillna(0) > 0
    daily_df["high_solar"] = daily_df["solar_radiation_mj"] > 20

    daily_df["wind_category"] = pd.cut(
        daily_df["wind_speed_mean_mph"],
        bins=[-1, 10, 20, float("inf")],
        labels=["all_activities", "water_sports_caution", "indoor_recommended"],
    )
    daily_df["cloud_category"] = pd.cut(
        daily_df["cloud_cover_pct"],
        bins=[-1, 30, 70, 100],
        labels=["sunny", "partly_cloudy", "overcast"],
    )

    # Creating key indicator relationship code keys to bridge lookup tables
    daily_df["weather_category_code"] = 1
    daily_df.loc[daily_df["cloud_cover_pct"] > 70, "weather_category_code"] = 2
    daily_df.loc[daily_df["precipitation_inches"] > 0.10, "weather_category_code"] = 3
    daily_df.loc[daily_df["wind_speed_mean_mph"] > 20, "weather_category_code"] = 4

    logger.info("Cleaned and normalized %s structural climate observations.", len(daily_df))
    return daily_df


