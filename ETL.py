def build_weekly_aggregation(daily_df: pd.DataFrame) -> pd.DataFrame:
    """Creates a downstream aggregated layer tracking time-series statistics by week."""
    weekly_df = daily_df.resample("W").agg(
        avg_temp_f=("temp_mean_f", "mean"),
        max_temp_f=("temp_max_f", "max"),
        min_temp_f=("temp_min_f", "min"),
        total_precipitation_inches=("precipitation_inches", "sum"),
        total_rain_inches=("rain_inches", "sum"),
        total_snowfall_inches=("snowfall_inches", "sum"),
        rainy_days=("has_precipitation", "sum"),
        avg_humidity_pct=("humidity_mean_pct", "mean"),
        avg_wind_speed_mph=("wind_speed_mean_mph", "mean"),
        avg_cloud_cover_pct=("cloud_cover_pct", "mean"),
        avg_solar_radiation_mj=("solar_radiation_mj", "mean"),
    )

    weekly_df = weekly_df.round(2)
    if weekly_df.empty:
        raise ValueError("Aggregation process anomaly: Resampling routine generated an empty dataset.")

    logger.info("Weekly analytics summary layer aggregation finalized successfully.")
    return weekly_df


def generate_activity_recommendations(daily_df: pd.DataFrame) -> pd.DataFrame:
    """Applies conditional logic matrices to formulate an analytics-ready scoring dataset."""
    recommendation_df = daily_df.copy()

    def recommend(row: pd.Series) -> str:
        if row["wind_speed_mean_mph"] > 20 or row["precipitation_inches"] > 0.25:
            return "Indoor activities recommended"
        if row["humidity_mean_pct"] > 80:
            return "Light outdoor activities; hydrate frequently"
        if row["cloud_cover_pct"] <= 30 and row["temp_mean_f"] <= 85:
            return "Outdoor sightseeing and walking tours"
        return "General outdoor activities acceptable"

    recommendation_df["recommended_activities"] = recommendation_df.apply(recommend, axis=1)

    # Mathematical calculation algorithm for localized comfort indexes
    recommendation_df["comfort_score"] = (
        100
        - (recommendation_df["temp_mean_f"] - 72).abs() * 1.5
        - recommendation_df["humidity_mean_pct"] * 0.20
        - recommendation_df["wind_speed_mean_mph"] * 0.50
        - recommendation_df["precipitation_inches"] * 20
    ).clip(lower=0, upper=100)

    # Subsetting and packing the finalized analytics-ready frame
    recommendation_df = recommendation_df[
        [
            "temp_mean_f",
            "humidity_mean_pct",
            "precipitation_inches",
            "wind_speed_mean_mph",
            "cloud_cover_pct",
            "weather_description",
            "comfort_score",
            "recommended_activities",
        ]
    ].round({"comfort_score": 1})

    logger.info("Downstream recommendation analytics scoring engine completed.")
    return recommendation_df


